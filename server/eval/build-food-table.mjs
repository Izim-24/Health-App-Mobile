// Builds data/food-table.json: per-100 g calories and macros the server uses instead of the model's own
// numbers once the model has named a food and its grams.
//
//   node eval/build-food-table.mjs
//
// - Generic ingredients: taken from Nutrition5k ingredient metadata (lab-weighed grams with USDA-based
//   nutrient values, CC BY 4.0). Each ingredient's density is constant in the dataset; we take the median
//   over every dish EXCEPT the dishes in the eval sets, and keep ingredients seen in at least 3 dishes.
// - Vietnamese dishes: data/vn-foods.json (approximate, typical recipes) — clearly marked "vn-approx".
import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';

const MIN_DISHES = 3;
const evalIds = new Set();
for (const f of ['eval/cases.json', 'eval/cases-holdout.json']) {
  // The case lists are generated locally by prepare-nutrition5k.mjs and are not in git.
  if (!existsSync(f)) { console.warn(`warning: ${f} not found — its dishes cannot be excluded`); continue; }
  for (const c of JSON.parse(await readFile(f, 'utf8'))) evalIds.add(c.source.split(' ').at(-1));
}

const per = new Map(); // name -> [{kcal, protein, carbs, fat}] per 100 g
for (const line of (await readFile('eval/nutrition5k/dish_metadata_cafe1.csv', 'utf8')).split('\n')) {
  const f = line.trim().split(',');
  if (f.length < 13 || evalIds.has(f[0])) continue;
  for (let i = 6; i + 6 < f.length; i += 7) {
    const [name, grams, kcal, fat, carbs, protein] = [f[i + 1], +f[i + 2], +f[i + 3], +f[i + 4], +f[i + 5], +f[i + 6]];
    if (!name || name === 'deprecated' || !(grams >= 2)) continue;
    const k = 100 / grams;
    if (!per.has(name)) per.set(name, []);
    per.get(name).push({ kcal: kcal * k, protein: protein * k, carbs: carbs * k, fat: fat * k });
  }
}

const median = (xs) => { const s = [...xs].sort((a, b) => a - b); const m = s.length >> 1; return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2; };
const r1 = (x) => Math.round(x * 10) / 10;
const generic = [...per.entries()]
  .filter(([, v]) => v.length >= MIN_DISHES)
  .map(([key, v]) => ({
    key, kcal: Math.round(median(v.map((x) => x.kcal))), protein: r1(median(v.map((x) => x.protein))),
    carbs: r1(median(v.map((x) => x.carbs))), fat: r1(median(v.map((x) => x.fat))), source: 'nutrition5k'
  }))
  .sort((a, b) => a.key.localeCompare(b.key));

const vn = JSON.parse(await readFile('data/vn-foods.json', 'utf8')).foods.map((f) => ({ ...f, source: 'vn-approx' }));
const keys = new Set(generic.map((f) => f.key));
const dup = vn.filter((f) => keys.has(f.key));
if (dup.length) throw new Error(`duplicate keys: ${dup.map((f) => f.key).join(', ')}`);

const table = [...generic, ...vn];
await writeFile('data/food-table.json', JSON.stringify({
  note: 'kcal and grams of protein/carbs/fat per 100 g as served. Generated by eval/build-food-table.mjs — do not edit by hand.',
  sources: {
    'nutrition5k': 'Nutrition5k ingredient metadata (Google Research, CC BY 4.0; USDA-based values), eval dishes excluded',
    'vn-approx': 'Approximate typical-recipe values for Vietnamese dishes (data/vn-foods.json)'
  },
  foods: table
}, null, 1));
console.log(`food-table.json: ${generic.length} Nutrition5k ingredients + ${vn.length} Vietnamese dishes (excluded ${evalIds.size} eval dishes)`);
